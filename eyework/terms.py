"""
«قبل أن تبدأ»: نصّه ونسخته
===========================
ما يوافق عليه صاحب الحساب: ما يُحفظ هنا، وما يُرسَل إلى مزوّد النموذج في كل بوابة.
النصّ هنا وحده، يخدمه `/api/choices` وتعرضه الواجهة كما هو، فلا يختلف ما يُقرأ
عمّا يُحفظ. ولكل نسخةٍ بصمة نصّها (`tests/unit/test_terms.py`): تغيير حرفٍ يُفشل
الاختبار حتى تُرفع النسخة.

النسخة تاريخ سريانها. ومن وافق على أقدم منها يوافق على الحالية عند دخوله التالي،
قبل أن يُرسَل له شيء (`web/deps.require_current_terms`).

النسخة الحالية نسخة الإشعار الذي يعرضه العميل الثابت (`static/index.html`) حتى
حزمة التبديل، ولا يتغيّر نصٌّ تحت نسخةٍ قائمة. فالنصّ هنا — شاشتان وسطرٌ لكل
بوابة — يُصدَر بتاريخ تلك الحزمة، التي تنقل بصمته من `PENDING_DIGEST` إلى
`DIGESTS` في الاختبار. كل البوابات تُعرض لكل مستخدم أيّاً كانت مهنته: المشغّل قد
ينقل حساباً إلى مهنةٍ أخرى، ونسخةٌ واحدة يجب أن تصدق على كل حساب.
"""

from __future__ import annotations

import re

from eyework.professions import Profession

__all__ = ["KEPT", "SENT", "SENT_INTRO", "SENT_OUTRO", "TERMS_VERSION", "is_current", "normalized_text", "notice"]

#: تاريخ إصدار هذا النصّ (YYYY-MM-DD)، بعد كل نسخةٍ في DIGESTS. يُضبط عند الإصدار (المواصفة §9.4).
TERMS_VERSION = "2026-10-09"

#: «ما يُحفظ هنا»، حرفاً بحرف (المواصفة §9.2). طريقة الاستخدام تُذكر لأن «يستعمل تتبّع
#: العين» معلومةٌ قريبة من الصحّية؛ والمقدّمة أدناه تقول إنها لا تُرسَل.
KEPT: tuple[str, ...] = (
    "يُحفظ: الاسم، وتاريخ الميلاد، والمهنة، وطريقة الاستخدام، وكلمة المرور مجزّأة.",
    "البريد لا يُحفظ، بل بصمته للدخول: لا يصله شيء، ولا يُستردّ الحساب به.",
    "وما تعمله في بوابتك لحسابك وحده، لا يراه مستخدمٌ غيرك.",
    "تحذف حسابك وبياناته متى شئت من «حسابي»، أو يحذفه بطلبك مَن يدير التطبيق؛ "
    "والنسخ الاحتياطية الأقدم تبقى حتى تُحذف.",
    "ومن يحاول التسجيل ببريدك يعرف أن لك حساباً هنا.",
)

SENT_INTRO = "يُرسَل إلى Anthropic خارج المملكة ما يحتاجه المساعد وحده، بلا اسمك ولا ميلادك ولا طريقة استخدامك:"
#: سطرٌ لكل بوابة (Profession)، أو لكل البوابات (None)، لا يتجاوز ستّين حرفاً. يكتبه مسار
#: البوابة (المواصفة §9.3): التسويق من إشعار العميل الثابت، والدعم من مواصفة مكتب الدعم
#: (§10.3)، والمخزون وسطر «كل البوابات» من مواصفة طبقة الذكاء (§6.4).
SENT: tuple[tuple[Profession | None, str], ...] = (
    (Profession.MARKETING, "التسويق: صورة المنتج ونصّه وما تطلبه من تعديل."),
    (Profession.SUPPORT, "الدعم الفني: رسائل العملاء بلا وسائل اتصال، وما تكتبه أنت."),
    (Profession.STOREKEEPER, "المخزون: بنود الفواتير والمرتجعات وأسماء أصنافك."),
    (None, "كل البوابات: سؤالك لسيمبول، وما في شاشتك، وما تقرؤه أدواته."),
)
SENT_OUTRO = "وتحذفه خلال 30 يوماً، إلا ما تُبقيه سياستها أو القانون."


def notice() -> dict:
    """الإشعار كما يعرضه العميل حرفياً، بنسخته. مجال السطر رمز المهنة أو ALL."""
    return {
        "version": TERMS_VERSION,
        "kept": list(KEPT),
        "sent": {
            "intro": SENT_INTRO,
            "items": [{"scope": scope.value if scope else "ALL", "text": text} for scope, text in SENT],
            "outro": SENT_OUTRO,
        },
    }


def normalized_text() -> str:
    """النصّ كلّه بترتيب عرضه، بمسافاتٍ موحّدة: ما تُحسب بصمته."""
    parts = [*KEPT, SENT_INTRO, *(text for _, text in SENT), SENT_OUTRO]
    return "\n".join(re.sub(r"\s+", " ", part).strip() for part in parts)


def is_current(accepted: str | None) -> bool:
    """
    هل تكفي النسخة التي وافق عليها الحساب؟ الحالية أو أحدث منها: بعد تراجعٍ عن إصدار
    لا يُحبس من وافق على الأحدث، والقاعدة لا تقبل الرجوع إلى أقدم (terms_version_backwards).
    والتواريخ YYYY-MM-DD تُقارن نصّاً. حساب الدعوة بلا نسخة، فيوافق أولاً.
    """
    return accepted is not None and accepted >= TERMS_VERSION
