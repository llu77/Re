"""
إشعار مكتب الدعم
================
ما يقرؤه موظف الدعم ويوافق عليه قبل أن يلصق أول رسالةٍ من عميل: ما يُلصق، وما يُحذف قبل
الحفظ، وما يُرسَل إلى Anthropic، وكم يبقى. النصّ هنا وحده: يخدمه `/api/support/home`
و`/api/support/settings`، وتعرضه الواجهة كما هو.

**النسخة تاريخ سريانها، ولا يتغيّر نصٌّ تحت نسخةٍ قائمة**: لكل نسخةٍ بصمة نصّها
(`tests/unit/test_support_notice.py`)، فتغيير حرفٍ يُفشل الاختبار حتى تُرفع النسخة. ومن
وافق على نسخةٍ أقدم يوافق على الجديدة قبل لصقه التالي أو طلبه التالي من سيمبول
(`web.deps.require_support_notice`)؛ وقراءة التذاكر وتحرير قاعدة المعرفة لا تنتظره. والقاعدة
ترفض كلام العملاء واستدعاء النموذج لمن لم يوافق على نسخةٍ قط (`support_notice_required`).

وحدةٌ نقية.
"""

from __future__ import annotations

import re

__all__ = ["LINES", "TITLE", "VERSION", "is_current", "normalized_text", "notice"]

VERSION = "2026-10-09"
TITLE = "قبل أن تلصق أول رسالة"
LINES: tuple[str, ...] = (
    "الصق من رسالة العميل ما يلزم لحلّ المشكلة وحده.",
    "يحذف التطبيق قبل الحفظ البريد والروابط وكل رقمٍ من تسعة أرقامٍ فأكثر؛ أما الأسماء داخل النصّ فلا يكتشفها، "
    "فاحذفها بنفسك.",
    "تُرسَل إلى Anthropic خارج المملكة رسائل التذكرة بعد الحذف، ومقالات قاعدة المعرفة، وما تكتبه من ردودٍ "
    "وملاحظات، ليكتب سيمبول المسودات ويراجعها. لا يُرسَل اسم العميل الذي تكتبه للتحية، ولا اسمك.",
    "وتحذفها Anthropic خلال 30 يوماً، وقد تُبقي ما تصنّفه مخالفاً لسياستها حتى سنتين، أو ما يُلزمها القانون بحفظه.",
    "تُحذف نصوص التذكرة بعد 30 يوماً من إغلاقها، ويبقى سجلّ القرارات بلا نصوصٍ سنةً ثم يُحذف.",
    "لا يرسل التطبيق شيئاً إلى العميل؛ أنت من يرسل الردّ من قناتك.",
    "وبالموافقة إقرارٌ بأن جهة العمل تسمح بمعالجة رسائل عملائها هنا وإرسالها إلى Anthropic.",
)


def normalized_text() -> str:
    """العنوان والأسطر بترتيب عرضها، بمسافاتٍ موحّدة: ما تُحسب بصمته."""
    return "\n".join(re.sub(r"\s+", " ", part).strip() for part in (TITLE, *LINES))


def is_current(accepted: str | None) -> bool:
    """الحالية أو أحدث منها (بعد تراجعٍ عن إصدار) تكفي؛ والأقدم أو لا شيء لا يكفي."""
    return accepted is not None and accepted >= VERSION


def notice(accepted: str | None) -> dict:
    return {"current": VERSION, "accepted": accepted, "title": TITLE, "lines": list(LINES)}
