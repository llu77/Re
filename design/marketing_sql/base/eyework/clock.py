"""
مصدر الزمن الوحيد في التطبيق
============================
بايثون هنا لا تقرأ ساعة الحائط أبداً: كل وقتٍ يُحفظ تكتبه القاعدة بـ`now()`،
فلا يختلف وقتان مصدرهما خادمان. وما تحتاجه الشيفرة — نوافذ حدود المعدّل
وحدها — ساعةٌ رتيبة لا ترجع إلى الوراء إن عُدّلت ساعة النظام.

اختبارٌ معماري يرفض `datetime.now()` و`date.today()` و`time.time()` في كل
التطبيق، و`time.monotonic()` خارج هذه الوحدة.
"""

from __future__ import annotations

import time

__all__ = ["monotonic"]


def monotonic() -> float:
    """ثوانٍ من نقطةٍ ثابتة غير محدّدة. للفروق وحدها، لا للتخزين."""
    return time.monotonic()
